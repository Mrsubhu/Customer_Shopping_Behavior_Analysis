 -- Q3)  Which are the top 5 product with the highest average review rating
 
 
SELECT item_purchased , ROUND(AVG(review_rating),2) AS average_product_rating
FROM customer_shopping
GROUP BY item_purchased
ORDER BY AVG(review_rating) DESC
LIMIT 5;

-- Q4) compare the average purchase amount between standard and express shipping 

SELECT shipping_type , 
ROUND(AVG(purchase_amount_usd),2)
FROM customer_shopping
WHERE shipping_type IN ('Standard', 'Express')
GROUP BY shipping_type;

-- Q5)  Do subscribed customers spend more? Compare average spend and total revenue between subscribers and non-subscribers 
SELECT * FROM  customer_shopping;

SELECT subscription_status ,
COUNT(customer_id) AS total_customers,
ROUND(AVG(purchase_amount_usd),2) AS avg_spend,
ROUND(SUM(purchase_amount_usd),2) AS total_revenue
FROM customer_shopping
GROUP BY subscription_status
ORDER BY total_revenue, avg_spend DESC;

-- Q6)  Which 5 product have the highest percentage of purchases  with discount applied?

SELECT item_purchased,
ROUND(SUM(CASE WHEN discount_applied = 'Yes' THEN 1 ELSE 0 END)/ COUNT(*)*100,2) AS discount_rate
FROM customer_shopping
GROUP BY item_purchased
ORDER BY discount_rate DESC 
LIMIT 5;

-- Q7  Segment customers into New, returning , and loyal based on their total
-- number of privious purchased , and show the count of each segment

  WITH customer_type AS (
  SELECT customer_id , previous_purchases,
  CASE 
	WHEN previous_purchases = 1 THEN 'New'
    WHEN previous_purchases BETWEEN 2 AND 10 THEN 'Returning'
    ELSE 'Loyal'
    END AS customer_segment 
FROM customer_shopping 
)
SELECT customer_segment , COUNT(*) AS "Number_of_customers"
FROM customer_type
GROUP BY customer_segment;

-- Q8 What are the top 3 most purchased products within each category?

WITH item_counts AS (
	SELECT category , item_purchased,
    COUNT(customer_id) AS total_orders,
    ROW_NUMBER() OVER(PARTITION BY category ORDER BY COUNT(customer_id) DESC) AS item_rank
    FROM customer_shopping
    GROUP BY category , item_purchased
)
SELECT item_rank , category , item_purchased, total_orders
FROM  item_counts
WHERE item_rank <=3;

-- Q9)  Are customers Who are repeat buyers (More than 5 previous purchases) also likely to  the subscriber

SELECT subscription_status ,
COUNT(customer_id) AS repeat_buyers
FROM customer_shopping 
WHERE previous_purchases > 5
GROUP BY subscription_status;

